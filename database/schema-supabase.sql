SELECT rm.hotel_id, p.id, p.amount, 15.00,
       ROUND(p.amount * 0.15, 2),
       p.amount - ROUND(p.amount * 0.15, 2),
       CASE WHEN p.id = 2 THEN 'PAID' ELSE 'PENDING' END,
       CASE WHEN p.id = 2 THEN 'BANK_TRANSFER' END,
