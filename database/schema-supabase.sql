-- =========================================================
-- SECURITY: lock the tables away from Supabase's public REST API
-- =========================================================
-- Row Level Security ON + no policies = the anon / authenticated roles
-- (the keys that ship in browsers) can read and write nothing. Your Spring
-- Boot backend connects as the `postgres` database role, which bypasses RLS.
ALTER TABLE hotels           ENABLE ROW LEVEL SECURITY;
ALTER TABLE hotel_images     ENABLE ROW LEVEL SECURITY;
ALTER TABLE rooms            ENABLE ROW LEVEL SECURITY;
ALTER TABLE room_images      ENABLE ROW LEVEL SECURITY;
ALTER TABLE room_amenities   ENABLE ROW LEVEL SECURITY;
ALTER TABLE guests           ENABLE ROW LEVEL SECURITY;
ALTER TABLE users            ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations     ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments         ENABLE ROW LEVEL SECURITY;
ALTER TABLE reviews          ENABLE ROW LEVEL SECURITY;
ALTER TABLE payouts          ENABLE ROW LEVEL SECURITY;

-- Belt and braces: also remove the privileges Supabase grants by default to
-- the API roles. Skipped automatically when run outside Supabase.
DO $$
DECLARE
    t   text;
    seq text;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
       AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN

        -- 1) The 12 tables above, and their identity sequences.
        FOREACH t IN ARRAY ARRAY['hotels','hotel_images','rooms','room_images','room_amenities',
                                 'guests','users','user_permissions','reservations','payments',
                                 'reviews','payouts']
        LOOP
            EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', t);
            seq := pg_get_serial_sequence(format('public.%I', t), 'id');
            IF seq IS NOT NULL THEN
                EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM anon, authenticated', seq);
            END IF;
        END LOOP;

        -- 2) FUTURE objects created by the role running this script (the
        --    `postgres` role in the SQL Editor) in the public schema. Without
        --    this, any table you add later - e.g. a new entity created by hand -
        --    would be readable and writable with the public anon key until
        --    you remembered to enable RLS on it. If you DO want a future table
        --    reachable from the browser, GRANT it explicitly and add RLS policies.
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES    FROM anon, authenticated;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated;
        ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM anon, authenticated;
    END IF;
END
$$;

