-- =========================================================
-- Hotel Reservation System - Supabase (PostgreSQL) schema + seed
-- =========================================================
-- HOW TO RUN
--   Supabase Dashboard -> SQL Editor -> New query -> paste this whole file
--   -> Run.  (Safe to re-run: it DROPS and recreates every table.)
--
-- WARNING: this file DROPS and recreates every table. To protect real data,
-- the SAFETY GUARD just below stops the script if these tables already
-- exist. On a fresh database it runs as-is. To intentionally wipe and
-- rebuild, change  confirm_reset := 'no'  to  'yes'  in the guard.
--
-- What is different from database/schema.sql (MySQL)?
--   * PostgreSQL syntax: BIGINT GENERATED BY DEFAULT AS IDENTITY,
--     DOUBLE PRECISION, TIMESTAMP, no CREATE DATABASE / USE.
--   * MySQL ENUM columns became VARCHAR + CHECK constraints. This is on
--     purpose: the Spring Boot entities store enums as plain strings
--     (@Enumerated(EnumType.STRING)), and a native PostgreSQL enum type would
--     make Hibernate fail with "column is of type X but expression is of
--     type character varying".
--   * Row Level Security is ENABLED on every table (see the end of the
--     file). Supabase exposes the `public` schema over its REST API with the
--     public anon key; without RLS anyone with that key could read - and
--     write - all bookings, guests and payments. The Spring Boot backend
--     connects with the database `postgres` role, which bypasses RLS, so it
--     keeps working. Do NOT add permissive policies unless you really want
--     the table reachable from the browser.
--   * The 20 hotels are REAL Thai hotels (5 each in Bangkok, Chiang Mai,
--     Phuket, Pattaya) with real addresses and latitude/longitude, which the
--     Hotel Detail page uses to draw the Longdo map pin. Coordinates come
--     from public hotel/travel listings and are accurate to roughly
--     100-300 m - good for a map pin, not for surveying. Descriptions are
--     written fresh for this project. Phone numbers are filled in only where
--     a public listing was found; e-mail is left empty on purpose.
--   * Prices (rooms.price_per_night) are in USD, like the original seed -
--     the frontend converts to THB (lib/currency.ts, 1 USD = 35 THB).
--
-- Hotel ids are assigned 1..20 in the order below. The backend's
-- DataInitializer creates owner1@hotel.com ... owner20@hotel.com by hotel id
-- order, so keep this order if you edit the file.
-- =========================================================

-- ---------------------------------------------------------
-- SAFETY GUARD - refuses to run over existing tables
-- ---------------------------------------------------------
-- The DROP TABLE statements below destroy data. If any of the project's
-- tables already exist, this block raises an error BEFORE anything is
-- dropped, so the rest of the script does not run.
-- To intentionally reset a development database, edit the line marked
-- <<< below to 'yes' and run again.
DO $$
DECLARE
    confirm_reset CONSTANT text := 'no';   -- <<< change to 'yes' to wipe and rebuild
BEGIN
    IF confirm_reset <> 'yes' AND (
           to_regclass('public.hotels')       IS NOT NULL
        OR to_regclass('public.reservations') IS NOT NULL
        OR to_regclass('public.users')        IS NOT NULL
        OR to_regclass('public.payments')     IS NOT NULL
    ) THEN
        RAISE EXCEPTION
            'Hotel tables already exist - refusing to DROP them. If you really want to wipe this database, set confirm_reset to ''yes'' in the SAFETY GUARD at the top of this script and run again.';
    END IF;
END
$$;

-- Drop in FK-safe order for repeatable runs
DROP TABLE IF EXISTS payouts          CASCADE;
DROP TABLE IF EXISTS reviews          CASCADE;
DROP TABLE IF EXISTS user_permissions CASCADE;
DROP TABLE IF EXISTS users            CASCADE;
DROP TABLE IF EXISTS payments         CASCADE;
DROP TABLE IF EXISTS reservations     CASCADE;
DROP TABLE IF EXISTS room_amenities   CASCADE;
DROP TABLE IF EXISTS room_images      CASCADE;
DROP TABLE IF EXISTS hotel_images     CASCADE;
DROP TABLE IF EXISTS rooms            CASCADE;
DROP TABLE IF EXISTS guests           CASCADE;
DROP TABLE IF EXISTS hotels           CASCADE;

-- ---------------------------------------------------------
-- Hotel
-- ---------------------------------------------------------
CREATE TABLE hotels (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    description     TEXT,
    address         VARCHAR(255),
    city            VARCHAR(100),
    country         VARCHAR(100),
    phone           VARCHAR(50),
    email           VARCHAR(150),
    star_rating     INTEGER CHECK (star_rating BETWEEN 1 AND 5),
    image_url       VARCHAR(500),
    latitude        DOUBLE PRECISION CHECK (latitude  BETWEEN -90  AND 90),
    longitude       DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
    -- The platform's cut of every payment for this hotel, as a percentage
    -- (15.00 = 15%). Finance-sensitive - never returned by the public
    -- GET /api/hotels/** endpoints. See entity/Hotel.java + PayoutService.
    commission_rate NUMERIC(5,2) NOT NULL DEFAULT 15.00,
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Hotel Images (extra gallery photos beyond hotels.image_url - managed
-- from /admin/hotels, which can upload several photos at once)
-- ---------------------------------------------------------
CREATE TABLE hotel_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id    BIGINT NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    category    VARCHAR(20) NOT NULL CHECK (category IN ('ROOM','BATHROOM','FACILITY','OTHER')),
    label       VARCHAR(150),
    image_url   VARCHAR(500) NOT NULL,
    sort_order  INTEGER DEFAULT 0
);

-- ---------------------------------------------------------
-- Room
-- ---------------------------------------------------------
CREATE TABLE rooms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id        BIGINT NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    room_number     VARCHAR(50) NOT NULL,
    room_type       VARCHAR(20) NOT NULL CHECK (room_type IN ('SINGLE','DOUBLE','TWIN','DELUXE','FAMILY','SUITE')),
    description     TEXT,
    price_per_night NUMERIC(10,2) NOT NULL CHECK (price_per_night >= 0),
    capacity        INTEGER NOT NULL CHECK (capacity > 0),
    bed_type        VARCHAR(100),
    size            DOUBLE PRECISION,
    floor           INTEGER,
    status          VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','OCCUPIED','MAINTENANCE')),
    image_url       VARCHAR(500),
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Room Images (extra photos per room beyond rooms.image_url - the
-- thumbnail strip on the Room Detail page. Managed via /admin/rooms.)
-- ---------------------------------------------------------
CREATE TABLE room_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    label       VARCHAR(150),
    image_url   VARCHAR(500) NOT NULL,
    sort_order  INTEGER DEFAULT 0
);

-- ---------------------------------------------------------
-- Room Amenities (grouped by category: Bed, Technology, Bathroom,
-- Accessibility, Kitchen - shown in RoomAmenitiesSidebar)
-- ---------------------------------------------------------
CREATE TABLE room_amenities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    category    VARCHAR(20) NOT NULL CHECK (category IN ('BED','TECHNOLOGY','BATHROOM','ACCESSIBILITY','KITCHEN')),
    title       VARCHAR(150) NOT NULL,
    description VARCHAR(255),
    icon        VARCHAR(50)
);

-- ---------------------------------------------------------
-- Guest
-- ---------------------------------------------------------
CREATE TABLE guests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(100) NOT NULL,
    last_name   VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    phone       VARCHAR(50),
    address     VARCHAR(255),
    city        VARCHAR(100),
    country     VARCHAR(100),
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Users (login identities - separate from Guest, the booking profile).
-- A GUEST-role user is linked 1:1 to a Guest row. A HOTEL_OWNER or
-- HOTEL_STAFF user is linked to exactly one Hotel (hotel_id). An ADMIN has
-- neither. Passwords are BCrypt hashes, so this table has NO seed rows
-- here: the backend's DataInitializer creates admin@hotel.com, the
-- guest1/2/3@test.com accounts and owner1..owner20@hotel.com on first
-- start-up. HOTEL_STAFF accounts are created later by each hotel owner.
-- ---------------------------------------------------------
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(150) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL,
    role        VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','HOTEL_OWNER','HOTEL_STAFF','GUEST')),
    guest_id    BIGINT UNIQUE REFERENCES guests(id) ON DELETE SET NULL,
    hotel_id    BIGINT REFERENCES hotels(id) ON DELETE SET NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Fine-grained permissions of a HOTEL_STAFF user (ignored for other roles).
CREATE TABLE user_permissions (
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    permission  VARCHAR(30) NOT NULL CHECK (permission IN ('MANAGE_HOTEL_INFO','MANAGE_ROOMS','MANAGE_RESERVATIONS','VIEW_FINANCE')),
    PRIMARY KEY (user_id, permission)
);

-- ---------------------------------------------------------
-- Reservation
-- ---------------------------------------------------------
CREATE TABLE reservations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_id          BIGINT NOT NULL REFERENCES guests(id) ON DELETE CASCADE,
    room_id           BIGINT NOT NULL REFERENCES rooms(id)  ON DELETE CASCADE,
    check_in_date     DATE NOT NULL,
    check_out_date    DATE NOT NULL,
    number_of_guests  INTEGER NOT NULL,
    number_of_rooms   INTEGER NOT NULL DEFAULT 1,
    special_request   TEXT,
    status            VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','CONFIRMED','CHECKED_IN','CHECKED_OUT','CANCELLED')),
    total_price       NUMERIC(10,2) NOT NULL,
    cancel_reason     TEXT,
    cancelled_at      TIMESTAMP,
    cancelled_by      VARCHAR(255),
    created_at        TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_dates CHECK (check_out_date > check_in_date)
);

-- ---------------------------------------------------------
-- Payment
-- ---------------------------------------------------------
CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id  BIGINT NOT NULL UNIQUE REFERENCES reservations(id) ON DELETE CASCADE,
    amount          NUMERIC(10,2) NOT NULL,
    payment_method  VARCHAR(20) NOT NULL CHECK (payment_method IN ('CREDIT_CARD','DEBIT_CARD','BANK_TRANSFER','CASH')),
    payment_status  VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (payment_status IN ('PENDING','PAID','FAILED','REFUNDED')),
    transaction_id  VARCHAR(100),
    paid_at         TIMESTAMP,
    created_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Review (one per reservation; only allowed once the stay is CHECKED_OUT -
-- see ReviewService.createReview). hotel_id is denormalized for a fast
-- average-rating lookup.
-- ---------------------------------------------------------
CREATE TABLE reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id        BIGINT NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    guest_id        BIGINT NOT NULL REFERENCES guests(id) ON DELETE CASCADE,
    reservation_id  BIGINT NOT NULL UNIQUE REFERENCES reservations(id) ON DELETE CASCADE,
    rating          INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT,
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Payout (platform -> hotel, net of commission). One per Payment; the
-- rate/amounts are snapshotted from hotels.commission_rate at creation.
-- ---------------------------------------------------------
CREATE TABLE payouts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id                BIGINT NOT NULL REFERENCES hotels(id) ON DELETE CASCADE,
    payment_id              BIGINT NOT NULL UNIQUE REFERENCES payments(id) ON DELETE CASCADE,
    gross_amount            NUMERIC(10,2) NOT NULL,
    commission_rate         NUMERIC(5,2)  NOT NULL,
    commission_amount       NUMERIC(10,2) NOT NULL,
    net_amount              NUMERIC(10,2) NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','PAID','CANCELLED')),
    payout_method           VARCHAR(20),
    transaction_reference   VARCHAR(100),
    paid_at                 TIMESTAMP,
    created_at              TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMP NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------
-- Indexes (PostgreSQL does not index foreign keys automatically)
-- ---------------------------------------------------------
CREATE INDEX idx_hotels_city             ON hotels(city);
CREATE INDEX idx_hotel_images_hotel      ON hotel_images(hotel_id);
CREATE INDEX idx_rooms_hotel             ON rooms(hotel_id);
CREATE INDEX idx_room_images_room        ON room_images(room_id);
CREATE INDEX idx_room_amenities_room     ON room_amenities(room_id);
CREATE INDEX idx_users_hotel             ON users(hotel_id);
CREATE INDEX idx_reservations_guest      ON reservations(guest_id);
CREATE INDEX idx_reservations_room_dates ON reservations(room_id, check_in_date, check_out_date);
CREATE INDEX idx_reservations_status     ON reservations(status);
CREATE INDEX idx_reviews_hotel           ON reviews(hotel_id);
CREATE INDEX idx_reviews_guest           ON reviews(guest_id);
CREATE INDEX idx_payouts_hotel           ON payouts(hotel_id);

