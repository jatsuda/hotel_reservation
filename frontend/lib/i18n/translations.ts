// The dictionaries are declared `as const`, so every string is a literal type
// ("Home" vs "หน้าแรก") and the Thai dictionary would not be assignable to the
// English one. Widen every string to `string`: the SHAPE (keys and nesting)
// must still match in both languages - a key missing from `th` is a compile
// error - but the wording may differ.
type WidenStrings<T> = T extends string ? string : { [K in keyof T]: WidenStrings<T[K]> };

export type TranslationShape = WidenStrings<typeof translations.en>;
